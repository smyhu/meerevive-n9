#!/bin/sh
# Builds the MeeRevive folder (engine + payload + components.list + md5sums.txt)
# from the project files. Usage: sh build.sh <output-dir> [public|private]
#   public  = only components we may redistribute (licences checked, LICENSES.txt)
#   private = everything (the authors' own phones)
set -e
P=${MEEREVIVE_SRC:-/mnt/project-files}   # folder with the component .debs (see README)
R=$P/rozpoznanie
ENG=$(cd "$(dirname "$0")/../engine" && pwd)
OUT=${1:?output dir}
VARIANT=${2:-private}
case "$VARIANT" in public|private) ;; *) echo "variant: public or private"; exit 1 ;; esac
PRIVATE_ONLY="cloudgps-fix"
rm -rf "$OUT"; mkdir -p "$OUT/payload/debs" "$OUT/payload/tls/own" "$OUT/payload/tls/original" "$OUT/payload/tools" "$OUT/payload/fonts" "$OUT/payload/meecast/qml" "$OUT/lib"
cp $ENG/engine.sh "$OUT/"; cp $ENG/lib/user-browser.sh "$OUT/lib/"

# spec: id|kind|source|requires|title|preremove|flags  (flags: replace = our fork replaces a store version even if newer)
SPEC="apt-sources|aptfix||| Disable dead apt mirrors|
tls|tls|||TLS 1.2 patch (n9-tls, OpenSSL 1.0.2u)|
emoji-font|font|||Emoji font (Symbola)|
webp|deb|$R/webp/qt4-imageformat-webp_1.4.0-3_armel.deb||WebP images (Qt plugin + webp2jpg)|
default-browser|browser|||System browser opens links (not Opera)|
waluty|deb|$P/waluty/waluty_1.1.8_armel.deb|tls|Waluty - currency rates|
lyrion-n9|deb|$R/muzyka/aplikacja/lyrion-n9_0.6.2_armel.deb||Lyrion - music player and remote|
meetranslate|deb|$R/tlumacz/meetranslate/meetranslate_0.1.1_armel.deb|tls|MeeTranslate - translator|
hal2027|deb|$R/agent-ai/hal2027/dist/hal2027_0.1.14_armel.deb|tls|HAL 2027 - AI assistant|
gpsinfo-n9|deb|$R/nawigacja/gpsinfo/dist/gpsinfo-n9_0.1.6_armel.deb||GPS Info - satellites and map|
ttrss|deb|$R/ttrss/aplikacja/ttrss_0.4.9_armel.deb|tls|Tiny Tiny RSS client||replace
netmee-n9|deb|$R/przegladarka/netmee/dist/netmee-n9_0.1.3_armel.deb|tls|NetMee - light web browser|
authmee-n9|deb|$R/authenticator/authmee/dist/authmee-n9_0.1.0_armel.deb||AuthMee - 2FA codes|
cloudgps-fix|deb|$R/nawigacja/cloudgps-fix/cloudgps-fix_1.1.0_armel.deb|tls|CloudGPS with search and routes (car, foot, bike)|cloudgps
modrana|deb|$R/nawigacja/modrana/modrana_0.43.4-n9.4_armel.deb|tls|modRana - maps and search||replace
meecast|deb|$P/meerevive/extras/meecast_1.1.33_armel.deb||MeeCast 1.1.33 weather (vasvlad)|
meecast-applet|deb|$P/meerevive/extras/meecast-applet-enable_0.2_all.deb|meecast|MeeCast weather in Events view (instead of AccuWeather)|
meecast-openmeteo|meecast|||MeeCast weather source Open-Meteo|
kanaly|tool|$R/feeds-n9/kanaly.sh||Feeds app manager (kanaly.sh: backup, restore, refresh)|"

{
echo "# MeeRevive component list ($VARIANT build, generated by build.sh $(date +%Y-%m-%d))"
echo "# id|kind|package|version|file|requires|title|depends|preremove|flags"
echo "$SPEC" | while IFS='|' read -r id kind src req title pre flags; do
  if [ "$VARIANT" = public ] && echo " $PRIVATE_ONLY " | grep -q " $id "; then continue; fi
  title=$(echo "$title" | sed 's/^ *//')
  if [ "$kind" = deb ]; then
    f=$(basename "$src"); cp "$src" "$OUT/payload/debs/"
    pkg=$(dpkg-deb -f "$src" Package); ver=$(dpkg-deb -f "$src" Version)
    deps=$(dpkg-deb -f "$src" Depends | tr ',' '\n' | sed 's/(.*//; s/|.*//; s/ //g' | grep -v '^$' | tr '\n' ' ' | sed 's/ $//')
    echo "$id|deb|$pkg|$ver|$f|$req|$title|$deps|$pre|$flags"
  elif [ "$kind" = tool ]; then
    f=$(basename "$src"); cp "$src" "$OUT/payload/tools/"
    echo "$id|tool|/usr/local/bin/$f||$f|$req|$title|tracker-utils||"
  else
    echo "$id|$kind|||||$title|||"
  fi
done
} > "$OUT/components.list"

# our TLS patch (github.com/smyhu/n9-tls, release 2) + Nokia originals (rollback, and removal of the old WW patch)
(cd $P/n9-tls/dist && md5sum -c md5sums.txt >/dev/null)
cp $P/n9-tls/dist/*.deb "$OUT/payload/tls/own/"
cp $R/latka-tls/N9-latka-tls/oryginaly-nokia/*.deb "$OUT/payload/tls/original/"
printf 'TLS 1.2 patch for Nokia N9: https://github.com/smyhu/n9-tls (MIT; OpenSSL licence for OpenSSL,\nLGPL for the rebuilt Qt/curl libraries, sources in that repository).\n' > "$OUT/payload/tls/own/README.txt"
cp $R/czcionki/Symbola_hint.ttf "$OUT/payload/fonts/"; cp $R/czcionki/Symbola-licencja.txt "$OUT/payload/fonts/Symbola-license.txt"
M=$R/meecast-open-meteo
cp $M/openmeteocom $M/open-meteo.com.xml $M/open-meteo.com.db $M/open-meteo.com.png "$OUT/payload/meecast/"
cp $M/poprawka-wyszukiwania/SearchField.qml "$OUT/payload/meecast/qml/"
cp $M/poprawka-wyszukiwania/SearchField.qml.oryginal "$OUT/payload/meecast/qml/SearchField.qml.original"
for q in StationsPage CountryPage; do
  cp $M/wyszukiwanie-online/$q.qml "$OUT/payload/meecast/qml/"
  cp $M/wyszukiwanie-online/$q.qml.oryginal "$OUT/payload/meecast/qml/$q.qml.original"
done
cp $M/wyszukiwanie-online/OnlineSearchPage.qml "$OUT/payload/meecast/qml/"
cp "$(dirname "$0")/LICENSES.txt" "$OUT/"

# list icons: an app's own icon (from its .desktop file), otherwise one of ours
# (art/components, made by tools/component-icons.py)
ART=$(cd "$(dirname "$0")/../art/components" && pwd)
ICONS="apt-sources:packages tls:lock emoji-font:emoji webp:image default-browser:browser meecast:weather meecast-applet:weather meecast-openmeteo:weather kanaly:document"
mkdir -p "$OUT/icons"
grep -v '^#' "$OUT/components.list" | while IFS='|' read -r id kind pkg ver file rest; do
  if [ "$kind" = deb ]; then
    deb="$OUT/payload/debs/$file"
    ic=$(dpkg-deb --fsys-tarfile "$deb" | tar -xO --wildcards './usr/share/applications/*.desktop' 2>/dev/null | sed -n 's/^Icon=//p' | head -1)
    case "$ic" in
      /*.png) dpkg-deb --fsys-tarfile "$deb" | tar -xO ".$ic" > "$OUT/icons/$id.png" 2>/dev/null || rm -f "$OUT/icons/$id.png" ;;
    esac
    [ -s "$OUT/icons/$id.png" ] || rm -f "$OUT/icons/$id.png"
  fi
  if [ ! -f "$OUT/icons/$id.png" ]; then
    g=$(echo " $ICONS " | sed -n "s/.* $id:\([a-z]*\) .*/\1/p")
    [ -n "$g" ] && cp "$ART/$g.png" "$OUT/icons/$id.png"
  fi
done
echo "$VARIANT" > "$OUT/VARIANT"
(cd "$OUT" && find . -type f ! -name md5sums.txt | sort | xargs md5sum > md5sums.txt)
du -sh "$OUT"
